#!/usr/bin/env python3
"""results/*.json  ->  paper/generated/numbers.tex  (+ numbers_manifest.json)

In LaTeX:   \\input{generated/numbers}   (preamble)   then   \\res{ours_miou_ade20k}
An undefined key renders as a bold ??key?? so a missing number can never look real.
Per-seed run files (<group>_s<seed>.json) are NOT exported: the paper cites their aggregate
(mean / std / ci95 from scripts/summarize_results.py), so no single lucky seed can be quoted.

    python3 scripts/export_numbers.py           # regenerate
    python3 scripts/export_numbers.py --check   # exit 1 if numbers.tex is stale (auditor)
"""
import argparse
import datetime as dt
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "paper", "generated")
KEY_OK = re.compile(r"^[A-Za-z0-9_.:-]+$")
PER_SEED = re.compile(r"^.+_s\d+\.json$")  # e.g. main_nav_ours_s2.json -> exported via agg_*.json only
# Only paper-facing results are exported (2026-11-08): multi-seed aggregates, deterministic eval-only runs, data statistics.
EXPORT_PREFIXES = ("agg_", "obs_", "diag_", "data_")

HEADER = r"""% AUTO-GENERATED by scripts/export_numbers.py -- DO NOT EDIT BY HAND.
% Source of truth: results/*.json (each stamped by scripts/run_logged.py).
\makeatletter
\providecommand{\res}[1]{\@ifundefined{res@#1}{\textbf{??\detokenize{#1}??}}{\@nameuse{res@#1}}}
"""
FOOTER = "\\makeatother\n"


def fmt(value, spec):
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, int) and spec is None:
        return str(value)
    if spec is None:
        a = abs(value)
        spec = ".1f" if a >= 10 else (".2f" if a >= 1 else ".3f")
    return format(value, spec)


EXPORT_ALL = False


def collect():
    defs, manifest, problems = {}, {}, []
    files = sorted(f for f in glob.glob(os.path.join(ROOT, "results", "*.json")))
    for path in files:
        rel = os.path.relpath(path, ROOT)
        if PER_SEED.match(os.path.basename(path)):
            continue  # per-seed runs are cited through their aggregate (scripts/summarize_results.py)
        if not EXPORT_ALL and not os.path.basename(path).startswith(EXPORT_PREFIXES):
            continue  # feasibility/diagnostic/tooling runs (t00_*, r01_*, pilot_* ...) are not paper numbers
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except (OSError, json.JSONDecodeError) as e:
            problems.append(f"ERROR {rel}: cannot parse ({e})")
            continue
        meta = data.get("_meta") or {}
        unlogged = meta.get("producer") != "scripts/run_logged.py"
        failed = meta.get("exit_code") not in (0, None) if meta else False
        if unlogged:
            problems.append(f"WARN  {rel}: no _meta from run_logged.py (provenance unknown)")
        if failed:
            problems.append(f"WARN  {rel}: run exit_code={meta.get('exit_code')}")
        formats = data.get("_format", {}) or {}
        for key, value in (data.get("metrics") or {}).items():
            if not KEY_OK.match(key):
                problems.append(f"WARN  {rel}: key '{key}' has characters LaTeX can't use; skipped")
                continue
            if not isinstance(value, (int, float)):
                problems.append(f"WARN  {rel}: metric '{key}' is not a number; skipped")
                continue
            text = fmt(value, formats.get(key))
            if key in defs and defs[key] != text:
                problems.append(f"ERROR key '{key}' defined twice with different values "
                                f"({manifest[key]['source']}={defs[key]} vs {rel}={text})")
                continue
            defs[key] = text
            manifest[key] = {
                "value": value, "formatted": text, "source": rel,
                "git_commit": meta.get("git_commit"), "exit_code": meta.get("exit_code"),
                "log_path": meta.get("log_path"), "unlogged": unlogged,
            }
    return defs, manifest, problems


def render(defs):
    body = "".join(f"\\@namedef{{res@{k}}}{{{v}}}\n" for k, v in sorted(defs.items()))
    return HEADER + body + FOOTER


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--all", action="store_true", help="export every logged result (debugging only; not for the paper)")
    args = ap.parse_args()
    global EXPORT_ALL
    EXPORT_ALL = args.all
    defs, manifest, problems = collect()
    tex = render(defs)
    tex_path = os.path.join(OUT_DIR, "numbers.tex")
    for p in problems:
        print(p, file=sys.stderr)

    if args.check:
        try:
            with open(tex_path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = ""
        if current != tex:
            print("STALE: paper/generated/numbers.tex does not match results/*.json. "
                  "Run: python3 scripts/export_numbers.py", file=sys.stderr)
            sys.exit(1)
        print(f"OK: {len(defs)} numbers in sync with results/")
        sys.exit(1 if any(p.startswith("ERROR") for p in problems) else 0)

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write(tex)
    with open(os.path.join(OUT_DIR, "numbers_manifest.json"), "w", encoding="utf-8") as f:
        json.dump({"generated": dt.datetime.now().isoformat(timespec="seconds"),
                   "numbers": manifest}, f, indent=2, ensure_ascii=False)
    print(f"wrote paper/generated/numbers.tex ({len(defs)} numbers)")
    sys.exit(1 if any(p.startswith("ERROR") for p in problems) else 0)


if __name__ == "__main__":
    main()
